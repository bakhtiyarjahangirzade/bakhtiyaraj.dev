// Bundle the game server (server/function.mjs + shared engines + supabase-js + chess.js) into one
// self-contained file for Supabase Edge Functions. The deployed entry point imports this file from GitHub
// pinned to a commit, so what runs is exactly what is in the repository at that commit.
import { build } from 'esbuild';
await build({
  entryPoints: ['server/function.mjs'], outfile: 'supabase/functions/play/index.js',
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', legalComments: 'none',
  banner: { js: '// Generated by scripts/build-function.mjs from server/ and public/games/. Do not edit by hand.' },
  plugins: [{ name: 'aliases', setup(b) {
    b.onResolve({ filter: /vendor\/chess\.mjs$/ }, () => ({ path: new URL('../node_modules/chess.js/dist/esm/chess.js', import.meta.url).pathname }));
    b.onResolve({ filter: /^npm:@supabase\/supabase-js/ }, () => ({ path: new URL('../node_modules/@supabase/supabase-js/dist/module/index.js', import.meta.url).pathname }));
  } }]
});
console.log('built supabase/functions/play/index.js');
