"""Creates the small, rights-safe Luna import fixtures in tests/fixtures/luna/ (drawn here, no third-party art).

Run: python3 -I scripts/luna/make-fixtures.py   (needs Pillow, reportlab, pypdf)
Every file is deterministic so the committed fixtures can be regenerated byte-for-byte where the libraries allow.
"""
import io, os, struct, zipfile, zlib
from PIL import Image, ImageDraw
from reportlab.lib.pagesizes import A5, landscape
from reportlab.pdfgen import canvas
from pypdf import PdfReader, PdfWriter

OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'tests', 'fixtures', 'luna')
os.makedirs(OUT, exist_ok=True)
COLOURS = ['#3d5a80', '#ee6c4d', '#98c1d9', '#293241', '#e0fbfc', '#81b29a', '#f2cc8f', '#6d597a', '#b56576', '#355070', '#eaac8b', '#56cfe1']

def page_image(n, w=600, h=840):
    im = Image.new('RGB', (w, h), 'white')
    d = ImageDraw.Draw(im)
    c = COLOURS[n % len(COLOURS)]
    d.rectangle([24, 24, w - 24, h - 24], outline='black', width=6)
    d.rectangle([48, 48, w - 48, h // 2], fill=c)
    d.ellipse([w // 2 - 80, h // 2 + 40, w // 2 + 80, h // 2 + 200], fill='black')
    d.text((60, h - 120), f'LUNA TEST PAGE {n}', fill='black')
    for k in range(n):  # n dots: the page number is visible without text rendering
        d.ellipse([60 + k * 28, 70, 80 + k * 28, 90], fill='white')
    return im

def save(name, data):
    with open(os.path.join(OUT, name), 'wb') as f: f.write(data)

def img_bytes(im, fmt, **kw):
    b = io.BytesIO(); im.save(b, fmt, **kw); return b.getvalue()

# 1. Multi-page PDF with mixed aspect ratios (portrait, portrait, landscape double page, portrait) and real text.
b = io.BytesIO()
pdf = canvas.Canvas(b, pagesize=A5, invariant=1)
pdf.setTitle('Luna test comic'); pdf.setAuthor('Luna fixtures')
for n, size in enumerate([A5, A5, landscape(A5), A5], start=1):
    pdf.setPageSize(size); w, h = size
    pdf.setFillColor(COLOURS[n]); pdf.rect(30, h / 2, w - 60, h / 2 - 40, fill=1, stroke=0)
    pdf.setFillColor('black'); pdf.setLineWidth(4); pdf.rect(20, 20, w - 40, h - 40)
    pdf.setFont('Helvetica-Bold', 26); pdf.drawString(44, h / 2 - 50, f'Luna PDF page {n}')
    pdf.setFont('Helvetica', 13); pdf.drawString(44, h / 2 - 80, 'Speech bubble text must stay legible: Salam, Luna!')
    pdf.setFont('Times-Roman', 11); pdf.drawString(44, 44, 'landscape double page' if w > h else 'portrait page')
    pdf.showPage()
pdf.save()
save('mixed.pdf', b.getvalue())

# 2. Password-protected copy and a truncated (corrupt) copy.
r = PdfReader(io.BytesIO(b.getvalue())); wr = PdfWriter()
for p in r.pages: wr.add_page(p)
wr.encrypt(user_password='luna', owner_password='luna-owner', algorithm='AES-128')
eb = io.BytesIO(); wr.write(eb); save('encrypted.pdf', eb.getvalue())
save('corrupt.pdf', b.getvalue()[: len(b.getvalue()) // 3])

# 3. CBZ with numbered pages whose lexical order is wrong (1, 10, 11, 2, ...), plus ComicInfo.xml and a folder.
def zip_bytes(entries, method=zipfile.ZIP_DEFLATED):
    zb = io.BytesIO()
    with zipfile.ZipFile(zb, 'w', method) as z:
        for name, data in entries:
            zi = zipfile.ZipInfo(name, date_time=(2026, 11, 3, 12, 0, 0)); zi.compress_type = method
            z.writestr(zi, data)
    return zb.getvalue()
pages = [(f'chapter-1/{n}.png' if n % 2 else f'chapter-1/{n}.jpg', img_bytes(page_image(n, 300, 420), 'PNG' if n % 2 else 'JPEG', quality=85)) for n in range(1, 12)]
pages.sort(key=lambda e: e[0])  # lexical: 1, 10, 11, 2, 3 ...
save('numbered.cbz', zip_bytes([('ComicInfo.xml', b'<?xml version="1.0"?><ComicInfo><Title>Luna test</Title></ComicInfo>')] + pages))

# 4. Individual raster pages in all three formats (and a landscape one).
save('page-01.jpg', img_bytes(page_image(1), 'JPEG', quality=88))
save('page-02.png', img_bytes(page_image(2), 'PNG'))
save('page-03.webp', img_bytes(page_image(3), 'WEBP', quality=85))
save('page-10-wide.webp', img_bytes(page_image(10, 1000, 640), 'WEBP', quality=85))

# 5. Things that must be refused.
save('fake-page.png', b'<!doctype html><html><body><script>alert(1)</script></body></html>')
save('fake-page.jpg', b'<svg xmlns="http://www.w3.org/2000/svg" onload="alert(1)"><rect width="10" height="10"/></svg>')
save('program.webp', b'MZ\x90\x00' + bytes(200))
save('comic.cbr', b'Rar!\x1a\x07\x01\x00' + bytes(64))
save('animation.gif', img_bytes(page_image(4, 200, 280), 'GIF'))
save('truncated.png', img_bytes(page_image(5), 'PNG')[:400])
good = img_bytes(page_image(6, 120, 160), 'PNG')
save('traversal.zip', zip_bytes([('01.png', good), ('../../evil.png', good)]))
save('absolute.zip', zip_bytes([('/etc/01.png', good)]))
save('nested.cbz', zip_bytes([('01.png', good), ('more/inner.zip', zip_bytes([('02.png', good)]))]))
save('not-images.zip', zip_bytes([('01.png', good), ('readme.html', b'<p>hi</p>')]))
save('renamed-html.cbz', zip_bytes([('01.png', good), ('02.png', b'<html><script>alert(1)</script></html>' * 3)]))

# Decompression bomb: 40 MB of zeros declared as a 1 KB image (the central directory lies about the size).
zeros = zlib.compressobj(9, zlib.DEFLATED, -15); comp = zeros.compress(bytes(40 * 1024 * 1024)) + zeros.flush()
def raw_zip(name, comp, usize_declared, crc):
    n = name.encode()
    local = struct.pack('<IHHHHHIIIHH', 0x04034b50, 20, 0, 8, 0, 0, crc, len(comp), usize_declared, len(n), 0) + n + comp
    central = struct.pack('<IHHHHHHIIIHHHHHII', 0x02014b50, 20, 20, 0, 8, 0, 0, crc, len(comp), usize_declared, len(n), 0, 0, 0, 0, 0, 0) + n
    end = struct.pack('<IHHHHIIH', 0x06054b50, 0, 0, 1, 1, len(central), len(local), 0)
    return local + central + end
save('bomb-lying.zip', raw_zip('01.png', comp, 1024, 0))
# Honest bomb: the declared size itself is far beyond limits/ratio.
save('bomb-ratio.zip', raw_zip('01.png', comp, 40 * 1024 * 1024, zlib.crc32(bytes(40 * 1024 * 1024))))
# Encrypted entry flag set.
enc = bytearray(zip_bytes([('01.png', good)]))
for sig, off in ((b'PK\x03\x04', 6), (b'PK\x01\x02', 8)):
    i = enc.find(sig); enc[i + off] |= 1
save('encrypted.zip', bytes(enc))
print('fixtures written to', os.path.normpath(OUT))
for f in sorted(os.listdir(OUT)): print(f'{os.path.getsize(os.path.join(OUT, f)):>9}  {f}')
